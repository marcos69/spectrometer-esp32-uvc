#!/usr/bin/env python3
"""Convert main/web_index.html -> main/web_index.h.
One C string per HTML line (no chunking heuristics). Run after edits:
  python3 tools/html2c.py
"""
import pathlib

src = pathlib.Path('main/web_index.html').read_text()
lines = src.split('\n')
out = pathlib.Path('main/web_index.h')
parts = ["/* AUTO-GENERATED by tools/html2c.py from web_index.html -- do not edit */\n",
         "static const char PAGE_HTML[] =\n"]
for i, ln in enumerate(lines):
    esc = ln.replace('\\', '\\\\').replace('"', '\\"')
    parts.append(f'    "{esc}\\n"\n')
parts[-1] = parts[-1].replace('\\n"\n', '";\n')
out.write_text(''.join(parts))
print(f"wrote {out}: {len(src)} chars page -> {out.stat().st_size} bytes header")
