#!/usr/bin/env python3
"""Generate savgol kernel tables for the ESP32-S3 spectrometer.
Replicates specfunctions.py exactly: window 17, deriv 0, orders 0..15,
kernel m = row 0 of pinv(B), convolve(m[::-1], padded, 'valid').
C-side contract: yhat[i] = sum_{t=0..16} m[t] * y_ext[i + 16 - t]
where y_ext = [pad8 | y[0..n-1] | pad8], i.e. yhat[i] = sum_t m[t]*y[i-(t-8)]
with reflect-pad at both edges (same edge values as specfunctions.py).
"""
import numpy as np

HALF = 8
MAX_ORDER = 15

def gen(order):
    # B rows k=-HALF..HALF, cols i=0..order : k**i  (same as specfunctions)
    B = np.array([[(k) ** i for i in range(order + 1)] for k in range(-HALF, HALF + 1)], dtype=float)
    m = np.linalg.pinv(B)[0].tolist()
    return m

out_lines = []
kernels = {}
for order in range(0, MAX_ORDER + 1):
    m = gen(order)
    kernels[order] = m
    out_lines.append("    { " + ", ".join(f"{v:.9e}" for v in m) + " },")

body = "\n".join(out_lines)
header = """/** Auto-generated by tools/gen_savgol.py -- DO NOT EDIT.
 * Savitzky-Golay kernels, window 17, deriv 0, orders 0..15.
 * yhat[i] = sum_{t=0..16} m[t] * y_ext[i + 16 - t], y_ext = [pad | y | pad],
 * pad values mirror specfunctions.py (self-reflective).
 */
const float sg_coeff[16][17] = {
""" + body + "\n};\n"

with open('/home/ubuntu/workspace/spectrometer-esp32/components/spectra/sg_coeff.c', 'w') as f:
    f.write(header)

# Self-check against scipy (interior should match; edges differ due to
# scipy's default 'interp' boundary)
try:
    from scipy.signal import savgol_filter
    rng = np.random.default_rng(42)
    y = (rng.random(636) * 60 + 100).astype(float)
    for order in (0, 1, 3, 7, 15):
        m = kernels[order]
        n = len(y)
        pad_l = y[0] - np.abs(y[1:HALF + 1][::-1] - y[0])     # 8 values
        pad_r = y[-1] + np.abs(y[-HALF - 1:-1][::-1] - y[-1])  # 8 values
        yfull = np.concatenate([pad_l, y, pad_r])
        # convolve(m[::-1], yfull, 'valid')
        mrev = m[::-1]
        outc = np.array([sum(mrev[j] * yfull[i + j] for j in range(2 * HALF + 1))
                         for i in range(len(yfull) - 2 * HALF)])
        ref = savgol_filter(y, 17, order)
        print(f"order {order:2d}: max interior err = {np.max(np.abs(outc[10:-10] - ref[10:-10])):.2e}")
except ImportError:
    print("scipy not available here; tables built from raw pinv (same as specfunctions.py).")
print("wrote sg_coeff.c")
