#!/usr/bin/env python3
"""Generate fixed-point IDCT cosine table + verify the C transform math.
JPEG IDCT: f(x,y) = (1/8) sum_uv F(u,v) C(u) cos((2x+1)u pi/16) C(v) cos((2y+1)v pi/16)
Q[u][k] = round(C(u) * cos((2k+1) u pi/16) * 2^13)
Separable: row pass T[x][v] = sum_u F[u][v]*Q[u][x]; col pass s = sum_v T Q[v][y]
f = s / 2^SHIFT (SHIFT determined empirically; expected 2^29 -> shift 29)
"""
import math, struct

SCALE = 1 << 13
Q = []
for u in range(8):
    cu = (1 / math.sqrt(2)) if u == 0 else 1.0
    row = [int(round(cu * math.cos((2 * k + 1) * u * math.pi / 16.0) * SCALE)) for k in range(8)]
    Q.append(row)

# C-language table
lines = ["/* Auto-generated by tools/gen_idct.py -- DO NOT EDIT. */",
         "#include <stdint.h>",
         "const int32_t idct_cos[8][8] = {"]
for row in Q:
    lines.append("    { " + ", ".join(str(v) for v in row) + " },")
lines.append("};")
with open('/home/ubuntu/workspace/spectrometer-esp32/components/jpegy/idct_cos.c', 'w') as f:
    f.write("\n".join(lines) + "\n")

# Verify: random 8x8 coefficient block, compare separable transform vs direct 2D IDCT
import random
random.seed(1)
for trial in range(200):
    F = [[random.randint(-200, 200) for _ in range(8)] for _ in range(8)]
    # direct 2D IDCT (reference, float)
    ref = []
    for x in range(8):
        row = []
        for y in range(8):
            s = 0.0
            for u in range(8):
                cu = (1 / math.sqrt(2)) if u == 0 else 1.0
                for v in range(8):
                    cv = (1 / math.sqrt(2)) if v == 0 else 1.0
                    s += F[u][v] * cu * cv * math.cos((2 * x + 1) * u * math.pi / 16.0) * math.cos((2 * y + 1) * v * math.pi / 16.0)
            row.append(s / 8.0)
        ref.append(row)
    # separable integer (C algorithm)
    T = [[0] * 8 for _ in range(8)]  # T[x][v]
    for v in range(8):
        for x in range(8):
            s = 0
            for u in range(8):
                s += F[u][v] * Q[u][x]
            T[x][v] = s
    out = []
    for x in range(8):
        row = []
        for y in range(8):
            s = 0
            for v in range(8):
                s += T[x][v] * Q[v][y]
            row.append(s / (1 << 29))  # SCALE^2 * 8
        out.append(row)
    err = max(abs(ref[x][y] - out[x][y]) for x in range(8) for y in range(8))
    if err > 1.5:
        print(f"trial {trial}: max err {err:.3f}  <-- FAIL")
        break
else:
    print("all 200 trials: max err < 1.5 gray levels — transform verified, final shift = 29")
